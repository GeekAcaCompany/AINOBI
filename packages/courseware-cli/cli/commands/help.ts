/** Verb words of a command path, without `<arg>` / `[opt]` placeholders. */
const verbOf = (path: string): string =>
  path
    .split(/\s+/)
    .filter((word) => word && !/^[<[]/.test(word) && !word.startsWith("--"))
    .join(" ");

const commandGroups = (): string[] => [...new Set(COMMAND_DOCS.map((doc) => verbOf(doc.path).split(" ")[0]))];

const findCommandDocsForTopic = (positionals: string[]): Record<string, unknown> | null => {
  const query = positionals.map((word) => word.trim().toLowerCase()).filter(Boolean).join(" ");
  if (!query) return null;
  const matchesQuery = (verb: string): boolean => verb === query || verb.startsWith(`${query} `);
  const commands = COMMAND_DOCS.filter(
    (doc) => matchesQuery(verbOf(doc.path)) || (doc.aliases ?? []).some((alias) => matchesQuery(verbOf(alias))),
  );
  if (commands.length === 0) return null;
  const group = query.split(" ")[0];
  return {
    topic: query,
    commands: commands.map((doc) => ({
      command: `ainobi ${doc.path}`,
      summary: doc.summary,
      ...(doc.aliases?.length ? { aliases: doc.aliases } : {}),
      ...(doc.requires_scene ? { requires_scene: true } : {}),
    })),
    ...(COMMAND_GROUP_REFERENCES[group] ? { read_next: COMMAND_GROUP_REFERENCES[group] } : {}),
  };
};

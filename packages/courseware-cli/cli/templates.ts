export const getUsage = (type: ElementType): ElementUsageDoc => {
  const factory = REGISTRY[type];
  if (!factory) {
    throw new Error(`No usage doc registered for element type "${type}".`);
  }
  return factory();
};

/**
 * Return a default scaffold for a given element type.
 * The CLI assigns the final element_id, so we omit it here intentionally.
 */
export const getElementScaffold = (type: ElementType): Record<string, unknown> => {
  const usage = getUsage(type);
  return JSON.parse(JSON.stringify(usage.template));
};

/** Lightweight catalog used by `ainobi help` and `ainobi help types`. */
export const listElementCatalog = (): { element_type: ElementType; description: string; required_fields: string[] }[] =>
  ELEMENT_TYPES.map((t) => {
    const u = getUsage(t);
    return {
      element_type: t,
      description: u.description,
      required_fields: u.required_fields,
    };
  });


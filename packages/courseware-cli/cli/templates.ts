export interface FieldDoc {
  path: string;
  type: string;
  required: boolean;
  default?: unknown;
  description?: string;
  enum?: readonly string[];
  managedByCli?: boolean;
}

export interface ElementUsageDoc {
  element_type: ElementType;
  description: string;
  template: Record<string, unknown>;
  required_fields: string[];
  fields: FieldDoc[];
  notes: string[];
}

const baseTemplate = (overrides: Record<string, unknown>): Record<string, unknown> => ({
  element_type: overrides.element_type,
  name: "",
  html: "",
  action_mappings: {},
  event_scripts: {},
  preset_script: "",
  position: { x: 0, y: 0 },
  size: { width: 1920, height: 1080 },
  timeline: { start_at: 0, end_at: 5000 },
  style: { opacity: 1, rotation_deg: 0, z_index: 0 },
  enter_effect: "none",
  exit_effect: "none",
  animations: [],
  keyframes: [],
  event_bindings: [],
  fps: 30,
  metadata: {},
  ...overrides,
});

/** Slide / group: no `html`; for embedded HTML use a child element with `element_type: "html"`. */
const containerBaseTemplate = (overrides: Record<string, unknown>): Record<string, unknown> => {
  const full = baseTemplate(overrides) as Record<string, unknown>;
  const { html: _omit, ...rest } = full;
  return rest;
};

